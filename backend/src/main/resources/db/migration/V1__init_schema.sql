-- Smart Cart schema (PostgreSQL 14+). Flyway owns the schema; Hibernate runs with ddl-auto=none.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(150)  NOT NULL UNIQUE,
    password_hash VARCHAR(100)  NOT NULL,
    role          VARCHAR(20)   NOT NULL DEFAULT 'ROLE_USER',
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT users_role_chk CHECK (role IN ('ROLE_USER', 'ROLE_ADMIN'))
);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64)  NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ  NOT NULL,
    revoked    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE products (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(200)   NOT NULL,
    description  TEXT,
    price        NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    mrp          NUMERIC(12, 2),
    stock        INT            NOT NULL DEFAULT 0 CHECK (stock >= 0),
    category_id  BIGINT         REFERENCES categories (id),
    image_url    VARCHAR(500),
    images       JSONB          NOT NULL DEFAULT '[]'::jsonb,
    attributes   JSONB          NOT NULL DEFAULT '{}'::jsonb,
    rating_avg   NUMERIC(3, 2)  NOT NULL DEFAULT 0,
    rating_count INT            NOT NULL DEFAULT 0,
    active       BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ    NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_price ON products (price);
CREATE INDEX idx_products_name_trgm ON products USING GIN (lower(name) gin_trgm_ops);
CREATE INDEX idx_products_attributes ON products USING GIN (attributes);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    quantity   INT    NOT NULL CHECK (quantity > 0),
    CONSTRAINT uq_cart_user_product UNIQUE (user_id, product_id)
);

CREATE TABLE orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT         NOT NULL REFERENCES users (id),
    status          VARCHAR(30)    NOT NULL,
    subtotal        NUMERIC(12, 2) NOT NULL,
    shipping_fee    NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_amount    NUMERIC(12, 2) NOT NULL,
    currency        VARCHAR(3)     NOT NULL DEFAULT 'INR',
    payment_gateway VARCHAR(20)    NOT NULL,
    shipping_name   VARCHAR(100)   NOT NULL,
    phone           VARCHAR(15)    NOT NULL,
    address_line1   VARCHAR(200)   NOT NULL,
    address_line2   VARCHAR(200),
    city            VARCHAR(100)   NOT NULL,
    state           VARCHAR(100)   NOT NULL,
    postal_code     VARCHAR(10)    NOT NULL,
    version         BIGINT         NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_orders_user ON orders (user_id, created_at DESC);
CREATE INDEX idx_orders_status ON orders (status);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id   BIGINT         NOT NULL REFERENCES products (id),
    product_name VARCHAR(200)   NOT NULL,
    image_url    VARCHAR(500),
    unit_price   NUMERIC(12, 2) NOT NULL,
    quantity     INT            NOT NULL CHECK (quantity > 0)
);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);

CREATE TABLE payments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    gateway            VARCHAR(20)  NOT NULL,
    gateway_order_id   VARCHAR(100) NOT NULL,
    gateway_payment_id VARCHAR(100),
    amount_paise       BIGINT       NOT NULL,
    currency           VARCHAR(3)   NOT NULL DEFAULT 'INR',
    status             VARCHAR(20)  NOT NULL,
    simulated          BOOLEAN      NOT NULL DEFAULT FALSE,
    failure_reason     VARCHAR(500),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_payment_gateway_order UNIQUE (gateway, gateway_order_id)
);
CREATE INDEX idx_payments_order ON payments (order_id);

CREATE TABLE reviews (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id        BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    rating            INT          NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title             VARCHAR(120),
    comment           TEXT,
    verified_purchase BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_review_user_product UNIQUE (user_id, product_id)
);
CREATE INDEX idx_reviews_product ON reviews (product_id, created_at DESC);

CREATE TABLE webhook_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gateway     VARCHAR(20)  NOT NULL,
    event_id    VARCHAR(150) NOT NULL,
    received_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_webhook_event UNIQUE (gateway, event_id)
);
