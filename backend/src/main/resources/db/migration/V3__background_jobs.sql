-- CO5: background tasks (email, invoice, notification) queued after a payment is verified.
-- Each row moves PENDING -> PROCESSING -> COMPLETED | FAILED; admins watch it live over WebSocket.
CREATE TABLE background_jobs (
    job_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT       NOT NULL REFERENCES orders (id),
    job_type   VARCHAR(20)  NOT NULL,
    status     VARCHAR(20)  NOT NULL,
    message    VARCHAR(500),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_background_jobs_order ON background_jobs (order_id);
